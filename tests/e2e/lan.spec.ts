import { test, expect } from '@playwright/test'

test('LAN host auto-configures and a private-IP mobile viewer works without internet or secure-context APIs', async ({ page, browser }) => {
  const configResponse = await page.request.get('http://127.0.0.1:8790/lan-config.json')
  const config = await configResponse.json()
  expect(config.viewerBases.length).toBeGreaterThan(0)
  const allowed = new Set(['127.0.0.1', ...config.viewerBases.map((item: { address: string }) => item.address)])
  const externalRequests: string[] = []
  const contexts = [page.context(), await browser.newContext({ viewport: { width: 390, height: 844 } })]
  for (const context of contexts) {
    await context.route('**/*', route => {
      if (allowed.has(new URL(route.request().url()).hostname)) return route.continue()
      externalRequests.push(route.request().url()); return route.abort()
    })
  }
  await page.goto('http://127.0.0.1:8790/')
  const tools = page.locator('.desktop-layout .tools-column')
  await expect(tools.getByRole('heading', { name: '區網廣播', exact: true })).toBeVisible()
  await expect(tools.getByLabel('建立房間金鑰')).toHaveCount(0)
  await tools.getByRole('button', { name: 'Add Act', exact: true }).click()
  await tools.getByRole('button', { name: '開啟區網廣播', exact: true }).click()
  await expect(tools.getByText('廣播中', { exact: true })).toBeVisible()
  const link = await tools.getByRole('link', { name: '開啟唯讀觀看畫面' }).getAttribute('href')
  const params = new URLSearchParams(new URL(link!).hash.slice(1))
  expect(new URL(link!).hostname).not.toBe('127.0.0.1')
  expect(new URL(params.get('service')!).host).toBe(new URL(link!).host)
  expect(link).not.toContain(config.key)
  const viewer = await contexts[1].newPage()
  await viewer.goto(link!)
  expect(await viewer.evaluate(() => window.isSecureContext)).toBe(false)
  await expect(viewer.getByRole('heading', { name: 'Act 1' })).toBeVisible()
  await expect(viewer.getByText('已同步 · 唯讀觀看')).toBeVisible()
  await expect(viewer.getByRole('button', { name: '保持螢幕亮起' })).toBeDisabled()
  const timer = page.locator('.desktop-layout .timer-column')
  await timer.getByRole('button', { name: 'Start Act 1' }).click()
  await expect(viewer.locator('.viewer-time')).toHaveText('00:00:01', { timeout: 5000 })
  await timer.getByRole('button', { name: 'Pause 暫停' }).click()
  await expect(viewer.locator('.pause-banner')).toContainText('演出暫停中')
  const frozen = await viewer.locator('.viewer-time').textContent()
  await expect(viewer.locator('.pause-banner')).toContainText('本次暫停 00:00:01')
  await expect(viewer.locator('.viewer-time')).toHaveText(frozen!)
  await viewer.reload()
  await expect(viewer.locator('.pause-banner')).toContainText('演出暫停中')
  await page.reload()
  await expect(tools.getByText('廣播中', { exact: true })).toBeVisible()
  const restoredLink = await tools.getByRole('link', { name: '開啟唯讀觀看畫面' }).getAttribute('href')
  expect(restoredLink).toBe(link)
  await timer.getByRole('button', { name: 'Resume 繼續演出' }).click()
  await expect(viewer.locator('.pause-banner')).toHaveCount(0)
  await tools.locator('.connection-panel').first().scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/showtimer-lan-host.png', fullPage: true })
  await viewer.screenshot({ path: '/tmp/showtimer-lan-viewer.png', fullPage: true })
  await tools.getByRole('button', { name: '停止廣播', exact: true }).click()
  await expect(viewer.getByText('廣播已結束', { exact: true })).toBeVisible()
  await viewer.goto(config.viewerBases[0].url)
  await expect(viewer.getByRole('heading', { name: '請掃描主控畫面的 QR Code' })).toBeVisible()
  expect(externalRequests).toEqual([])
  await contexts[1].close()
})
