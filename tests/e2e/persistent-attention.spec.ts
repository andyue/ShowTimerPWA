import { test, expect } from '@playwright/test'
test('Persistent reminders: drag, persistent screen cue and finish on both ends', async ({ page, browser }) => {
 page.on('dialog', d => d.accept())
 await page.goto('http://127.0.0.1:8790/')
 const tools = page.locator('.desktop-layout .tools-column')
 const timer = page.locator('.desktop-layout .timer-column')
 const marks = page.locator('.desktop-layout .qmark-column')
 await tools.getByRole('button', { name: 'Add Act', exact: true }).click()
 await tools.getByRole('button', { name: 'Start LAN broadcast', exact: true }).click()
 await expect(tools.getByText('Broadcasting', { exact: true })).toBeVisible()
 const link = await tools.getByRole('link', { name: 'Open read-only viewer' }).getAttribute('href')
 const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
 const viewer = await context.newPage()
 await viewer.goto(link!)
 await expect(viewer.getByText('Synced · read-only viewer')).toBeVisible()
 await timer.getByRole('button', { name: 'Start Act 1' }).click()
 for (const note of ['Lights GO', 'Sound GO', 'Curtain']) {
  await marks.getByRole('button', { name: 'Add Mark', exact: true }).click()
  await marks.locator('textarea').last().fill(note)
 }
 const handle = marks.getByRole('button', { name: 'Drag Q1', exact: true })
 const from = await handle.boundingBox()
 const to = await marks.getByRole('button', { name: 'Drag Q3', exact: true }).boundingBox()
 await page.mouse.move(from!.x + 10, from!.y + 10)
 await page.mouse.down()
 await page.mouse.move(to!.x + 10, to!.y + 10, { steps: 8 })
 await page.mouse.up()
 await expect(marks.locator('textarea').last()).toHaveValue('Lights GO')
 await expect(marks.locator('textarea').first()).toHaveValue('Sound GO')
 const clock = timer.getByRole('button', { name: 'Send screen reminder' })
 const go = page.getByRole('button', { name: 'GO', exact: true })
 await expect(go).toHaveCount(0)
 await clock.click()
 await expect(go).toBeVisible()
 await expect(viewer.getByRole('button', { name: 'GO', exact: true })).toHaveCount(0)
 await expect(viewer.locator('.attention-active')).toHaveCount(1)
 await expect(page.locator('.attention-active')).toHaveCount(1)
 await expect(viewer.locator('.attention-active')).toHaveCSS('animation-duration', '0.25s')
 await viewer.waitForTimeout(3300)
 await expect(viewer.locator('.attention-active')).toHaveCount(1)
 await viewer.reload()
 await expect(viewer.locator('.attention-active')).toHaveCount(1)
 await go.click()
 await expect(go).toHaveCount(0)
 await expect(viewer.locator('.attention-complete')).toHaveCount(1)
 await expect(page.locator('.attention-complete')).toHaveCount(1)
 await expect(viewer.locator('.attention-border')).toHaveCount(0, { timeout: 6500 })
 await marks.getByRole('button', { name: 'Remind viewers of Q3', exact: true }).click()
 await expect(go).toBeVisible()
 await expect(viewer.locator('.viewer-note-only')).toHaveText('Lights GO')
 await expect(viewer.locator('.attention-active')).toHaveCount(1)
 await expect(viewer.locator('.viewer-time, .viewer-marks-table, .viewer-timer-panel')).toHaveCount(0)
 await marks.getByRole('button', { name: 'Remind viewers of Q1', exact: true }).click()
 await expect(viewer.locator('.viewer-note-only')).toHaveText('Sound GO')
 await go.click()
 await expect(go).toHaveCount(0)
 await expect(page.locator('.attention-complete')).toHaveCount(1)
 await expect(viewer.locator('.attention-complete')).toHaveCount(1)
 await expect(viewer.locator('.viewer-note-only')).toHaveText('Sound GO')
 await expect(viewer.locator('.attention-border')).toHaveCount(0, { timeout: 6500 })
 await expect(viewer.locator('.viewer-time')).toHaveText(/00:00:/)
 await expect(page.locator('.attention-border')).toHaveCount(0)
 await context.close()
})


test('mobile touch drag preserves notes and saves order', async ({ browser }) => {
 const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true })
 const page = await context.newPage()
 await page.addInitScript(() => {
  if (localStorage.getItem('showtimer-current-project')) return
  const date = new Date().toISOString()
  localStorage.setItem('showtimer-current-project', JSON.stringify({ format: 'ShowTimer', version: 2, projectId: 'touch-test', projectName: 'Touch test', createdAt: date, updatedAt: date,
   segments: [{ id: 'act', name: 'Act 1', type: 'act', order: 0, plannedSeconds: 30 }], results: [],
   cueMarks: ['First note', 'Second note', 'Third note'].map((note, i) => ({ id: `cue-${i}`, label: `Q${i+1}`, note, segmentId: 'act', segmentName: 'Act 1', segmentType: 'act', segmentOrder: 0, elapsedSeconds: i, createdAt: date, displayOrder: i })) }))
 })
 await page.goto('/')
 await page.getByRole('button', { name: 'Q Marks', exact: true }).click()
 const marks = page.locator('.mobile-layout')
 const a = (await marks.getByRole('button', { name: 'Drag Q1', exact: true }).boundingBox())!
 const b = (await marks.getByRole('button', { name: 'Drag Q3', exact: true }).boundingBox())!
 const cdp = await context.newCDPSession(page)
 const x = a.x + a.width/2, y = a.y + a.height/2, end = b.y + b.height/2
 await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
 for (let step=1; step<=10; step++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y+(end-y)*step/10 }] })
 await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
 await expect(marks.locator('textarea').first()).toHaveValue('Second note')
 await expect(marks.locator('textarea').last()).toHaveValue('First note')
 await page.reload()
 await page.getByRole('button', { name: 'Q Marks', exact: true }).click()
 await expect(marks.locator('textarea').last()).toHaveValue('First note')
 await context.close()
})
